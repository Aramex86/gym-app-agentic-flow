#!/usr/bin/env node
// scripts/map.mjs - deterministic repo map for agent context (no tokens spent).
// Walks the source tree, extracts each module's exports, writes docs/context/repo-map.md.
// Usage: node scripts/map.mjs   (or: pnpm map)
// Config at the top; project-agnostic out of the box.

import { readdirSync, statSync, readFileSync, mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative, extname } from 'node:path';

const ROOT = process.cwd();
const OUT = 'docs/context/repo-map.md';

const SKIP_DIRS = new Set([
  'node_modules', '.git', 'dist', 'build', '.vite', 'coverage',
  '.pipeline', 'docs', 'tasks', 'evals', '.claude', '.github',
]);
const CODE_EXT = new Set(['.ts', '.tsx', '.js', '.mjs', '.jsx', '.py', '.go']);
const SCRIPT_EXT = new Set(['.mjs', '.cjs']);

// files whose whole content is part of the contract
const FULL_TEXT = new Set(['AGENTS.md', 'agents-pipeline.yaml', 'package.json']);

function walk(dir, files = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name) || entry.name.startsWith('.')) continue;
      walk(join(dir, entry.name), files);
    } else if (entry.isFile()) {
      const ext = extname(entry.name);
      if (CODE_EXT.has(ext) || FULL_TEXT.has(entry.name)) files.push(join(dir, entry.name));
    }
  }
  return files;
}

function exportsOf(file) {
  const rel = relative(ROOT, file);
  const name = file.split(/[\\/]/).pop();
  if (FULL_TEXT.has(name)) return null; // handled elsewhere
  if (file.endsWith('.yaml')) return null;
  const text = readFileSync(file, 'utf8');
  const lines = text.split('\n');
  const exp = [];
  for (let i = 0; i < lines.length; i++) {
    const l = lines[i].trim();
    if (l.startsWith('export ') || l.startsWith('export default') || l.startsWith('module.exports') ||
        l.match(/^(def |class |func |function |async function )/) ) {
      exp.push(`  L${i + 1}: ${l.slice(0, 120)}`);
    }
  }
  return { rel, lines: lines.length, exp };
}

const all = walk(ROOT);

// --- header: project contract files, whole content (they ARE the map) ---
let out = `# repo-map (auto-generated by scripts/map.mjs; root: ${ROOT})\n`;
out += `<!-- refresh:  node scripts/map.mjs   |   consumed by planner/tests prompts -->\n\n`;

for (const f of ['AGENTS.md', 'agents-pipeline.yaml']) {
  if (existsSync(join(ROOT, f))) {
    out += `## ${f}\n\n\`\`\`\n${readFileSync(join(ROOT, f), 'utf8').trim()}\n\`\`\`\n\n`;
  }
}

// --- tree ---
const dirs = new Map();
for (const f of all) {
  const d = relative(ROOT, f).replace(/[\\/][^\\/]*$/, '');
  if (!dirs.has(d)) dirs.set(d, []);
  dirs.get(d).push(f);
}
out += `## Directory tree\n\n`;
const sortedDirs = [...dirs.keys()].sort();
for (const d of sortedDirs) {
  const files = dirs.get(d);
  const stat = files.map((f) => exportsOf(f)).filter(Boolean);
  const nLines = stat.reduce((a, s) => a + s.lines, 0);
  out += `### ${d}/  (${stat.length} modules, ${nLines} lines)\n`;
  for (const s of stat) {
    out += `#### ${s.rel}  (${s.lines} lines)\n`;
    out += s.exp.length ? '```text\n' + s.exp.join('\n') + '\n```\n' : `_no exports found_\n`;
  }
  out += '\n';
}

mkdirSync(join(ROOT, 'docs/context'), { recursive: true });
writeFileSync(OUT, out);
const size = statSync(OUT).size;
console.log(`repo-map written: ${OUT} (${(size / 1024).toFixed(1)} KB, ${all.length} files scanned)`);
